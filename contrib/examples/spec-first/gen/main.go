package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

type operation struct {
	Name          string
	Method        string
	Path          string
	ErrorStatuses []int
}

func main() {
	specPath := flag.String("spec", "openapi.json", "path to OpenAPI spec")
	outPath := flag.String("out", "spec_gen.go", "output Go file")
	flag.Parse()

	loader := openapi3.NewLoader()
	spec, err := loader.LoadFromFile(*specPath)
	if err != nil {
		exitf("load spec: %v", err)
	}
	if err := spec.Validate(loader.Context); err != nil {
		exitf("validate spec: %v", err)
	}

	ops := collectOperations(spec)
	if len(ops) == 0 {
		exitf("no operations found")
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by spec-first example; DO NOT EDIT.\n")
	buf.WriteString("package main\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"net/http\"\n\n")
	buf.WriteString("\t\"github.com/aatuh/api-toolkit/ports\"\n")
	buf.WriteString(")\n\n")

	writeRoutes(&buf, ops)
	writeStatusErrors(&buf, ops)

	src, err := format.Source(buf.Bytes())
	if err != nil {
		exitf("format output: %v", err)
	}
	if err := os.WriteFile(*outPath, src, 0o600); err != nil {
		exitf("write output: %v", err)
	}
}

func collectOperations(spec *openapi3.T) []operation {
	if spec == nil || spec.Paths == nil {
		return nil
	}
	var ops []operation
	used := make(map[string]int)
	for path, item := range spec.Paths.Map() {
		if item == nil {
			continue
		}
		for method, op := range item.Operations() {
			if op == nil {
				continue
			}
			name := op.OperationID
			if strings.TrimSpace(name) == "" {
				name = defaultOperationID(method, path)
			}
			name = exportedName(name)
			if name == "" {
				continue
			}
			if count := used[name]; count > 0 {
				name = fmt.Sprintf("%s%d", name, count+1)
			}
			used[name]++
			ops = append(ops, operation{
				Name:          name,
				Method:        strings.ToUpper(method),
				Path:          path,
				ErrorStatuses: errorStatuses(op.Responses),
			})
		}
	}
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].Name == ops[j].Name {
			return ops[i].Method < ops[j].Method
		}
		return ops[i].Name < ops[j].Name
	})
	return ops
}

func errorStatuses(responses *openapi3.Responses) []int {
	if responses == nil {
		return nil
	}
	var statuses []int
	for code := range responses.Map() {
		val, err := strconv.Atoi(code)
		if err != nil {
			continue
		}
		if val >= 400 && val <= 599 {
			statuses = append(statuses, val)
		}
	}
	sort.Ints(statuses)
	return statuses
}

func writeRoutes(buf *bytes.Buffer, ops []operation) {
	buf.WriteString("const (\n")
	for _, op := range ops {
		fmt.Fprintf(buf, "\t%sMethod = http.Method%s\n", op.Name, titleCase(strings.ToLower(op.Method)))
		fmt.Fprintf(buf, "\t%sPath = %q\n", op.Name, op.Path)
	}
	buf.WriteString(")\n\n")
	buf.WriteString("type Handlers interface {\n")
	for _, op := range ops {
		fmt.Fprintf(buf, "\t%s(http.ResponseWriter, *http.Request)\n", op.Name)
	}
	buf.WriteString("}\n\n")
	buf.WriteString("func RegisterRoutes(r ports.HTTPRouter, h Handlers) {\n")
	buf.WriteString("\tif r == nil || h == nil {\n\t\treturn\n\t}\n")
	for _, op := range ops {
		switch op.Method {
		case http.MethodGet:
			fmt.Fprintf(buf, "\tr.Get(%sPath, h.%s)\n", op.Name, op.Name)
		case http.MethodPost:
			fmt.Fprintf(buf, "\tr.Post(%sPath, h.%s)\n", op.Name, op.Name)
		case http.MethodPut:
			fmt.Fprintf(buf, "\tr.Put(%sPath, h.%s)\n", op.Name, op.Name)
		case http.MethodDelete:
			fmt.Fprintf(buf, "\tr.Delete(%sPath, h.%s)\n", op.Name, op.Name)
		default:
			fmt.Fprintf(buf, "\t// TODO: register %s %s manually\n", op.Method, op.Path)
		}
	}
	buf.WriteString("}\n\n")
}

func writeStatusErrors(buf *bytes.Buffer, ops []operation) {
	buf.WriteString("type StatusError interface {\n")
	buf.WriteString("\terror\n")
	buf.WriteString("\tStatusCode() int\n")
	buf.WriteString("}\n\n")
	for _, op := range ops {
		for _, status := range op.ErrorStatuses {
			name := fmt.Sprintf("%s%s", op.Name, statusName(status))
			fmt.Fprintf(buf, "type %s struct { Detail string }\n", name)
			fmt.Fprintf(buf, "func (e %s) Error() string { return e.Detail }\n", name)
			fmt.Fprintf(buf, "func (e %s) StatusCode() int { return %s }\n\n", name, statusConstant(status))
		}
	}
}

func statusName(code int) string {
	switch code {
	case 400:
		return "BadRequest"
	case 401:
		return "Unauthorized"
	case 403:
		return "Forbidden"
	case 404:
		return "NotFound"
	case 409:
		return "Conflict"
	case 422:
		return "UnprocessableEntity"
	case 429:
		return "TooManyRequests"
	case 500:
		return "InternalServerError"
	case 503:
		return "ServiceUnavailable"
	}
	return fmt.Sprintf("Status%d", code)
}

func statusConstant(code int) string {
	switch code {
	case 400:
		return "http.StatusBadRequest"
	case 401:
		return "http.StatusUnauthorized"
	case 403:
		return "http.StatusForbidden"
	case 404:
		return "http.StatusNotFound"
	case 409:
		return "http.StatusConflict"
	case 422:
		return "http.StatusUnprocessableEntity"
	case 429:
		return "http.StatusTooManyRequests"
	case 500:
		return "http.StatusInternalServerError"
	case 503:
		return "http.StatusServiceUnavailable"
	}
	return strconv.Itoa(code)
}

func defaultOperationID(method, path string) string {
	parts := strings.Split(path, "/")
	var tokens []string
	tokens = append(tokens, strings.ToLower(method))
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		part = strings.Trim(part, "{}")
		tokens = append(tokens, part)
	}
	return strings.Join(tokens, "_")
}

func exportedName(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}
	if isPlainIdentifier(raw) {
		name := raw
		if name[0] >= 'a' && name[0] <= 'z' {
			name = strings.ToUpper(name[:1]) + name[1:]
		}
		if name[0] >= '0' && name[0] <= '9' {
			name = "Op" + name
		}
		return name
	}
	tokens := splitTokens(raw)
	if len(tokens) == 0 {
		return ""
	}
	var b strings.Builder
	for _, token := range tokens {
		b.WriteString(titleCase(token))
	}
	name := b.String()
	if name == "" {
		return ""
	}
	if name[0] >= '0' && name[0] <= '9' {
		return "Op" + name
	}
	return name
}

func isPlainIdentifier(s string) bool {
	for i := 0; i < len(s); i++ {
		ch := s[i]
		if (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9') {
			continue
		}
		return false
	}
	return true
}

func splitTokens(s string) []string {
	var tokens []string
	var cur []rune
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			cur = append(cur, r)
			continue
		}
		if len(cur) > 0 {
			tokens = append(tokens, string(cur))
			cur = nil
		}
	}
	if len(cur) > 0 {
		tokens = append(tokens, string(cur))
	}
	return tokens
}

func titleCase(s string) string {
	if s == "" {
		return ""
	}
	s = strings.ToLower(s)
	return strings.ToUpper(s[:1]) + s[1:]
}

func exitf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
